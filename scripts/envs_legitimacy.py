"""Check that each data-out task rewards the skill it claims, not a shortcut.

    uv run python scripts/envs_legitimacy.py            # every task in envs/
    uv run python scripts/envs_legitimacy.py --task readout_drift

Three checks per task, each graded by the task's own evaluate.py:

- lazy and leak solutions (envs/<task>/checks/, listed in checks/expect.json): constant
  answers, "always changed", "always other", reading the grader's stack frames, importing the
  grader, loading it from disk. Each must score at most trivial + MARGIN on the public seed and
  the first `check_seeds` paper seeds. A check marked `public_seed_open` may win on the public
  seed by design (its instances are public) and is judged on the paper seeds only.
- data ablation: the reference, with every instance's data swapped for another instance's
  (MISMATCH_ABLATE=1, eval/_isolate.py), must fall to trivial + MARGIN. A task must need its data.
- the reference must beat trivial + MARGIN, so the task has room a known method reaches.

Writes docs/envs-legitimacy.md and exits 1 if any check fails.
"""

from __future__ import annotations

import argparse
import json
import sys
from statistics import mean

from qec_drift import paths
from qec_drift.agent import envs_grade as eg
from qec_drift.agent.envs_kit import ENVS, TASKS

MARGIN = 0.05
DOC = paths.REPO_ROOT / "docs" / "envs-legitimacy.md"


def check_seeds() -> list[int | None]:
    return [None, *eg.CONFIG["paper_seeds"][: eg.CONFIG["check_seeds"]]]


def scores(task: str, rel: str, name: str, ablate: bool = False) -> dict[str, float]:
    """Native score per check seed (public and the first paper seeds)."""
    reps = eg.reports(task, ENVS / task / rel, name, check_seeds(), ablate)
    return {tag: rep["score"] for tag, rep in reps.items()}


def task_rows(task: str) -> list[dict]:
    """One row per check: its worst score against the trivial floor on the same seeds."""
    trivial = scores(task, eg.BASELINES["trivial"], "trivial")
    floor = {s: v + MARGIN for s, v in trivial.items()}
    rows = []
    expect = json.loads((ENVS / task / "checks" / "expect.json").read_text())
    for c in expect:
        if c["kind"] not in ("lazy", "leak"):
            continue
        got = scores(task, f"checks/{c['file']}", c["file"].removesuffix(".py"))
        judged = {s: v for s, v in got.items() if not (c.get("public_seed_open") and s == "public")}
        worst = max(judged, key=lambda s: judged[s] - floor[s])
        rows.append(
            dict(
                check=c["file"],
                kind=c["kind"],
                why=c["why"],
                score=judged[worst],
                bar=floor[worst],
                ok=judged[worst] <= floor[worst],
            )
        )
    ablated = scores(task, eg.BASELINES["reference"], "reference_swapped_data", ablate=True)
    rows.append(
        dict(
            check="reference, swapped data",
            kind="ablation",
            why="The reference on another instance's data must lose its edge.",
            score=mean(ablated.values()),
            bar=mean(floor.values()),
            ok=mean(ablated.values()) <= mean(floor.values()),
        )
    )
    ref = scores(task, eg.BASELINES["reference"], "reference")
    rows.append(
        dict(
            check="reference",
            kind="room",
            why="A known method must beat the floor.",
            score=mean(ref.values()),
            bar=mean(floor.values()),
            ok=mean(ref.values()) > mean(floor.values()),
        )
    )
    return rows


def markdown(results: dict[str, list[dict]]) -> str:
    lines = [
        "# Data-out tasks: lazy, leak and ablation checks",
        "",
        "Generated by scripts/envs_legitimacy.py; do not edit. Hard tier, public seed and the "
        f"first {eg.CONFIG['check_seeds']} paper seeds. Native scores; the bar is trivial + "
        f"{MARGIN} on the same seed (the reference must stay above it).",
    ]
    for task, rows in results.items():
        lines += [
            "",
            f"## {task}",
            "",
            "| check | kind | score | bar | result | why |",
            "|---|---|---|---|---|---|",
        ]
        for r in rows:
            result = "pass" if r["ok"] else "FAIL"
            lines.append(
                f"| {r['check']} | {r['kind']} | {r['score']:.3f} | {r['bar']:.3f} | "
                f"{result} | {r['why']} |"
            )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--task", choices=sorted(TASKS))
    a = ap.parse_args(argv)
    results = {t: task_rows(t) for t in ([a.task] if a.task else TASKS)}
    DOC.write_text(markdown(results))
    print(DOC.read_text())
    return 0 if all(r["ok"] for rows in results.values() for r in rows) else 1


if __name__ == "__main__":
    sys.exit(main())
